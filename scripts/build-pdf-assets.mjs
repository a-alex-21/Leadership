/** Prepare offline image data for canvas export from file:// URLs. */
import { readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const html = await readFile(resolve(root, 'index.html'), 'utf8');
const paths = [...new Set([...html.matchAll(/<img\b[^>]*src="([^"]+)"/g)].map(m => m[1]))];
const images = {};
for (const path of paths) {
  if (!path.startsWith('assets/images/') || !path.endsWith('.png')) {
    throw new Error(`Unsupported export image: ${path}`);
  }
  images[path] = `data:image/png;base64,${(await readFile(resolve(root, path))).toString('base64')}`;
}
await writeFile(resolve(root, 'assets/pdf-images.js'),
  '// Generated by scripts/build-pdf-assets.mjs. Do not edit.\n' +
  `window.presentationPdfImages = Object.freeze(${JSON.stringify(images)});\n`);
console.log(`Prepared ${paths.length} offline PDF images.`);
